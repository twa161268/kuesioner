const router = require('express').Router();
const { requireRole } = require('../middlewares/requireRole');
const dashboard = require('../controllers/dashboard.controller');
const pemohon = require('../controllers/pemohon.controller');
const sesi = require('../controllers/sesi.controller');
const kuesioner = require('../controllers/kuesioner.controller');
router.use(requireRole('admin', 'super_admin'));
router.get('/', dashboard.index);
router.get('/pemohon', pemohon.index);
router.get('/pemohon/tambah', pemohon.createForm);
router.post('/pemohon', pemohon.create);
router.get('/pemohon/:id/ubah', pemohon.editForm);
router.post('/pemohon/:id', pemohon.update);
router.post('/pemohon/:id/status', pemohon.toggleStatus);
router.get('/sesi', sesi.index);
router.get('/sesi/tambah', sesi.createForm);
router.post('/sesi', sesi.create);
router.get('/sesi/:id/kelola', sesi.editForm);
router.get('/sesi/:id/detail', sesi.detail);
router.post('/sesi/:id/akses-baru', requireRole('super_admin'), sesi.reissueAccess);
router.post('/sesi/:id/tes/:detailId/hitung', requireRole('super_admin'), sesi.calculateResult);
router.get('/sesi/:id/tes/:detailId/hasil', requireRole('super_admin'), sesi.viewResult);
router.post('/sesi/:id/tes/:detailId/terbitkan', requireRole('super_admin'), sesi.publishResult);
router.get('/sesi/:id/tes/:detailId/hasil.pdf', requireRole('super_admin'), sesi.adminPdf);
router.post('/sesi/:id/tes/:detailId/ulang', sesi.resetTest);
router.post('/sesi/:id', sesi.update);
router.get('/kuesioner', requireRole('super_admin'), kuesioner.index);
router.get('/kuesioner/tambah', requireRole('super_admin'), kuesioner.createForm);
router.post('/kuesioner', requireRole('super_admin'), kuesioner.create);
router.get('/kuesioner/:id/ubah', requireRole('super_admin'), kuesioner.editForm);
router.post('/kuesioner/:id', requireRole('super_admin'), kuesioner.update);

const instrumen = require('../controllers/instrument.controller');
router.get('/:resource', requireRole('super_admin'), instrumen.index);
router.get('/:resource/tambah', requireRole('super_admin'), instrumen.createForm);
router.post('/:resource', requireRole('super_admin'), instrumen.create);
router.get('/:resource/:id/ubah', requireRole('super_admin'), instrumen.editForm);
router.post('/:resource/:id', requireRole('super_admin'), instrumen.update);
router.post('/:resource/:id/hapus', requireRole('super_admin'), instrumen.remove);
module.exports = router;
